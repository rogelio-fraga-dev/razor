-- V2.1: Cria a tabela `appointments` de forma versionada.
-- Historicamente a tabela era criada pelo Hibernate (ddl-auto), sem migracao Flyway.
-- Isso quebrava qualquer banco novo (CI/deploy limpo): a V3 fazia ALTER TABLE numa
-- tabela inexistente e o `ddl-auto: validate` falhava. Esta migracao formaliza o
-- schema legado (datas como VARCHAR) para que a V3 possa converte-lo em tipos fortes.
--
-- IF NOT EXISTS: idempotente em bancos legados onde a tabela ja existe (producao).
CREATE TABLE IF NOT EXISTS appointments (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_phone   VARCHAR(20) NOT NULL,
    customer_name    VARCHAR(255),
    appointment_date VARCHAR(50),   -- legado: "hoje" / "DD/MM" -> convertido para DATE na V3
    appointment_time VARCHAR(20),   -- legado: "HH:mm" / "HHhMM" / "HHh" -> convertido para TIME na V3
    service          VARCHAR(255),
    payment_status   VARCHAR(30),   -- enum PaymentStatus (@Enumerated STRING)
    notified         BOOLEAN NOT NULL DEFAULT FALSE,
    thanked          BOOLEAN NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMP,
    updated_at       TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_appointments_phone ON appointments(customer_phone);
